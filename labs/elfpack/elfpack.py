# ============================================================
# ELF parsing
# ============================================================
def parse_elf(path):
    d = open(path, "rb").read()
    if d[:4] != b"\x7fELF":
        sys.exit(f"{path}: bukan ELF")
    if d[4] != 2:
        sys.exit(f"{path}: hanya ELF64")
    if struct.unpack_from("<H", d, 18)[0] != 62:
        sys.exit(f"{path}: hanya x86-64")
    e_type = struct.unpack_from("<H", d, 16)[0]   # 2=ET_EXEC 3=ET_DYN
    e_entry = struct.unpack_from("<Q", d, 24)[0]
    e_phoff = struct.unpack_from("<Q", d, 32)[0]
    e_phentsize = struct.unpack_from("<H", d, 54)[0]
    e_phnum = struct.unpack_from("<H", d, 56)[0]
    segs = []
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        p_type = struct.unpack_from("<I", d, off)[0]
        if p_type != 1:                            # PT_LOAD
            continue
        segs.append((
            struct.unpack_from("<Q", d, off + 8)[0],   # p_offset
            struct.unpack_from("<Q", d, off + 16)[0],  # p_vaddr
            struct.unpack_from("<Q", d, off + 32)[0],  # p_filesz
            struct.unpack_from("<Q", d, off + 40)[0],  # p_memsz
            struct.unpack_from("<I", d, off + 4)[0],   # p_flags
        ))
    if not segs:
        sys.exit(f"{path}: tidak ada PT_LOAD")
    return d, e_type, e_entry, segs


def prot_convert(pf):
    p = 0
    if pf & 4:
        p |= 1   # PF_R -> PROT_READ
    if pf & 2:
        p |= 2   # PF_W -> PROT_WRITE
    if pf & 1:
        p |= 4   # PF_X -> PROT_EXEC
    return p


# ============================================================
# RLE + XOR
# ============================================================
def rle_encode(data):
    """Format: control & 0x80 -> run, count=(c&0x7f)+1 (1..128), value byte.
    control < 0x80 -> literal. Byte >= 0x80 selalu di-encode sebagai run."""
    out = bytearray()
    i, n = 0, len(data)
    while i < n:
        b = data[i]
        j = i + 1
        while j < n and data[j] == b and j - i < 128:
            j += 1
        run = j - i
        if b >= 0x80 or run >= 3:
            out.append(0x80 | (run - 1))
            out.append(b)
            i = j
        else:
            out.append(b)
            i += 1
    return bytes(out)


def xorfy(blob, key):
    return bytes(c ^ key for c in blob)


def blob_lines(b):
    lines = []
    for i in range(0, len(b), 12):
        lines.append("    .byte " + ", ".join("0x%02x" % x for x in b[i:i + 12]))
    return "\n".join(lines)


# ============================================================
# Builders
# ============================================================
def build_static(d, e_type, e_entry, segs, key, out_path):
    min_v = min(s[1] for s in segs)
    max_v = max(s[1] + s[3] for s in segs)
    blob = b""
    seg_lines = []
    for (p_off, p_vaddr, p_filesz, p_memsz, p_flags) in segs:
        data = d[p_off:p_off + p_filesz]
        enc = xorfy(rle_encode(data), key)
        seg_lines.append(f"    .quad {p_vaddr - min_v}      # off")
        seg_lines.append(f"    .quad {p_filesz}      # filesz")
        seg_lines.append(f"    .quad {p_memsz}      # memsz")
        seg_lines.append(f"    .quad {prot_convert(p_flags)}      # prot")
        seg_lines.append(f"    .quad {len(blob)}      # blob_off")
        seg_lines.append(f"    .quad {len(enc)}      # blob_len")
        seg_lines.append("    .quad 0")
        blob += enc
    stub = fill(STUB_STATIC, dict(
        MIN_V=min_v,
        RANGE=max_v - min_v,
        FLAGS=0x22 | (0x10 if e_type == 2 else 0),   # MAP_FIXED utk ET_EXEC
        NSEGS=len(segs),
        ENTRY_OFF=e_entry - min_v,
        KEY=key,
        SEGS="\n".join(seg_lines),
        BLOB=blob_lines(blob),
    ))
    with tempfile.TemporaryDirectory() as td:
        asm = os.path.join(td, "s.s")
        obj = os.path.join(td, "s.o")
        open(asm, "w").write(stub)
        subprocess.run(["as", asm, "-o", obj], check=True)
        try:
            subprocess.run(
                ["ld", "-pie", "--no-dynamic-linker", "-o", out_path, obj],
                check=True,
            )
        except subprocess.CalledProcessError:
            # fallback: biarkan PT_INTERP (ld-linux tetap jalan ke _start)
            subprocess.run(["ld", "-pie", "-e", "_start", "-o", out_path, obj],
                           check=True)
    os.chmod(out_path, 0o755)


def build_dynamic(d, key, out_path):
    enc = xorfy(rle_encode(d), key)
    stub = fill(STUB_DYN, dict(
        BLOB=",\n".join("0x%02x" % x for x in enc),
        BLOB_LEN=len(enc),
        OUT_LEN=len(d),
        KEY=key,
    ))
    with tempfile.TemporaryDirectory() as td:
        src = os.path.join(td, "s.c")
        exe = os.path.join(td, "s")
        open(src, "w").write(stub)
        subprocess.run(
            ["cc", "-static", "-nostdlib", "-fno-stack-protector",
             "-fno-builtin", "-no-pie", "-O2", "-o", exe, src],
            check=True,
        )
        data = open(exe, "rb").read()
    open(out_path, "wb").write(data)
    os.chmod(out_path, 0o755)


def main():
    ap = argparse.ArgumentParser(description="ELF runtime packer (gaya UPX)")
    ap.add_argument("-m", "--mode", choices=["static", "dynamic"], required=True)
    ap.add_argument("-p", "--payload", required=True)
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("-s", "--seed", type=int, default=None)
    args = ap.parse_args()

    d, e_type, e_entry, segs = parse_elf(args.payload)
    key = random.Random(args.seed).randrange(256)

    if args.mode == "static":
        build_static(d, e_type, e_entry, segs, key, args.out)
        kind = "static in-memory loader"
    else:
        build_dynamic(d, key, args.out)
        kind = "dynamic temp+execve loader"

    orig = hashlib.sha256(d).hexdigest()[:16]
    packed = hashlib.sha256(open(args.out, "rb").read()).hexdigest()[:16]
    print(f"packed  : {args.out}  ({kind})")
    print(f"  asli  : {len(d)} bytes  sha256={orig}...")
    print(f"  packed: {os.path.getsize(args.out)} bytes  sha256={packed}...")
    print(f"  ratio : {os.path.getsize(args.out) / len(d):.1%}")


if __name__ == "__main__":
    main()

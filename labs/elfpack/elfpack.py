#!/usr/bin/env python3
"""
elfpack.py — ELF runtime packer (gaya UPX) untuk binary asli.

Dua mode:

  --mode static   In-memory loader untuk ET_EXEC / static binary.
                  Stub assembly (PIE, syscall langsung, tanpa libc):
                    mmap(range) -> decode tiap PT_LOAD (RLE+XOR) di p_vaddr
                    -> zero-fill bss -> mprotect per segment -> jmp e_entry.
                  Payload TIDAK pernah menyentuh disk. Stack (argc/argv/envp)
                  dibiarkan utuh dari kernel, jadi payload jalan normal.

  --mode dynamic  Temp-file loader untuk ET_DYN / dynamic binary (PIE,
                  linked libc — termasuk binary C++ seperti xcb).
                  Stub C (-static -nostdlib):
                    decode seluruh file ELF ke memori -> tulis file temp unik
                    /tmp/.elx_<pid> -> fork -> child execve (kernel loader
                    normal, PT_INTERP dihormati) -> parent wait4 + unlink.
                  File temp hanya hidup beberapa milidetik.

Keduanya pakai kompresi RLE (efektif untuk ELF: banyak byte 0) + XOR
1-byte key acak. Tiap run -> key & blob beda -> sha256 hasil beda.

Peringatan jujur: ini LAB studi teknik packing untuk binary sendiri.
RLE+XOR 1-byte bukan kripto kuat — hanya menyamarkan signature statis.
"""

import argparse
import hashlib
import os
import random
import struct
import subprocess
import sys
import tempfile

# Token placeholder @@X@@ dipakai karena assembly AT&T penuh karakter '$'
# (immediate) yang bentrok dengan string.Template / str.format.
def fill(tpl, mapping):
    for k, v in mapping.items():
        tpl = tpl.replace("@@" + k + "@@", str(v))
    return tpl


